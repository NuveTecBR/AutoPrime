-- AUTOPRIME SEMINOVOS — SUPABASE / POSTGRESQL (sa-east-1) COM RLS ATIVO
-- ============================================================================

CREATE TABLE IF NOT EXISTS usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  senha_hash TEXT NOT NULL,
  cargo TEXT NOT NULL DEFAULT 'vendedor' CHECK (cargo IN ('lojista', 'vendedor')),
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS veiculos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  marca TEXT NOT NULL,
  modelo TEXT NOT NULL,
  versao TEXT NOT NULL,
  ano_fabricacao INTEGER NOT NULL,
  ano_modelo INTEGER NOT NULL,
  preco NUMERIC(12,2) NOT NULL CHECK (preco > 0),
  quilometragem INTEGER NOT NULL DEFAULT 0,
  cambio TEXT NOT NULL,
  combustivel TEXT NOT NULL,
  cor TEXT NOT NULL,
  final_placa INTEGER NOT NULL,
  carroceria TEXT NOT NULL,
  destaque BOOLEAN NOT NULL DEFAULT FALSE,
  laudo_cautelar TEXT NOT NULL DEFAULT '100% Aprovado Dekra',
  garantia_meses INTEGER NOT NULL DEFAULT 12,
  imagem_url TEXT NOT NULL,
  itens_serie TEXT NOT NULL,
  descricao TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'Disponível',
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS simulacoes_leads (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  protocolo TEXT NOT NULL UNIQUE,
  veiculo_id BIGINT NOT NULL REFERENCES veiculos(id) ON DELETE CASCADE,
  tipo_atendimento TEXT NOT NULL DEFAULT 'Simulação & Test-Drive',
  nome_cliente TEXT NOT NULL,
  telefone TEXT NOT NULL,
  email TEXT,
  valor_entrada NUMERIC(12,2) NOT NULL DEFAULT 0,
  prazo_meses INTEGER NOT NULL DEFAULT 48,
  valor_parcela NUMERIC(12,2) NOT NULL DEFAULT 0,
  taxa_juros_mensal NUMERIC(5,2) NOT NULL DEFAULT 1.49,
  possui_troca BOOLEAN NOT NULL DEFAULT FALSE,
  descricao_troca TEXT,
  consentimento_lgpd BOOLEAN NOT NULL DEFAULT TRUE,
  status TEXT NOT NULL DEFAULT 'Novo Lead',
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS solicitacoes_lgpd (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  protocolo TEXT NOT NULL UNIQUE,
  nome_titular TEXT NOT NULL,
  email_titular TEXT NOT NULL,
  tipo_direito TEXT NOT NULL,
  detalhes TEXT,
  status TEXT NOT NULL DEFAULT 'Recebido',
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Ativação estrita de Row Level Security (RLS)
ALTER TABLE usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE veiculos ENABLE ROW LEVEL SECURITY;
ALTER TABLE simulacoes_leads ENABLE ROW LEVEL SECURITY;
ALTER TABLE solicitacoes_lgpd ENABLE ROW LEVEL SECURITY;

-- Políticas de Segurança
CREATE POLICY "Leitura publica de veiculos" ON veiculos FOR SELECT USING (true);
CREATE POLICY "Apenas backend service role gerencia usuarios" ON usuarios FOR ALL USING (false);
CREATE POLICY "Apenas backend service role gerencia leads" ON simulacoes_leads FOR ALL USING (false);
CREATE POLICY "Apenas backend service role gerencia lgpd" ON solicitacoes_lgpd FOR ALL USING (false);
